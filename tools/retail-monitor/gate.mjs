import {appendFile} from 'node:fs/promises';
const token=process.env.GITHUB_TOKEN;
const event=process.env.GITHUB_EVENT_NAME||'manual';
if(!token)throw Error('Missing GitHub token');
const hours=50*60000;
const cutoff=Date.parse('2026-11-01T19:59:59.999Z');
const url='https://api.github.com/repos/Web-Usov/dashboard/contents/data.json?ref=gh-pages';
const res=await fetch(url,{headers:{Accept:'application/vnd.github+json',Authorization:'Bearer '+token},signal:AbortSignal.timeout(18000)});
if(!res.ok)throw Error('Could not read gh-pages data.json to schedule collection, HTTP '+res.status);
const entry=await res.json();const d=JSON.parse(Buffer.from(entry.content.replace(/\s/g,''),'base64').toString('utf8'));
const last=d.retailAutomated?.lastAttemptAt||d.lastCheckAt;
const lastMs=Date.parse(last||'');
const ageMs=Number.isFinite(lastMs)?Date.now()-lastMs:Infinity;
const isExpired=Date.now()>cutoff;
const shouldRun=!isExpired&&(event==='push'||ageMs>=hours);
const output='should_run='+String(shouldRun)+'\n';
await appendFile(process.env.GITHUB_OUTPUT,output);
const minutes=Number.isFinite(ageMs)?Math.max(0,Math.floor(ageMs/60000)):'unknown';
const summary='### Schedule gate\n\nEvent: \`'+event+'\` | Previous retail check: \`'+(last||'never')+'\` ('+minutes+' min ago). | Collector: **'+(shouldRun?'RUN':'SKIP')+'**.\n\nScheduled or externally-dispatched runs only collect when the previous attempt is at least 50 minutes old. Push-based test runs may force collection during the active monitoring window. No fabricated datapoints are inserted.\n';
await appendFile(process.env.GITHUB_STEP_SUMMARY,summary);
console.log(summary);
